/**
 * app/firebase-messaging-sw.js/route.ts
 * ─────────────────────────────────────────────────────────────────────────────
 * Dynamic route handler that serves the Firebase Cloud Messaging service worker
 * at /firebase-messaging-sw.js with Firebase config values injected from
 * server-side environment variables.
 *
 * Why a route handler instead of a static file?
 *   Service workers cannot access process.env or window. By serving the SW
 *   through this route handler, we can safely inject NEXT_PUBLIC_ Firebase
 *   config values at request time — no hardcoded credentials in the repo.
 *
 * The handler sets:
 *   Content-Type: application/javascript   — required for SW registration
 *   Service-Worker-Allowed: /              — allows the SW to control scope /
 *   Cache-Control: no-cache                — always get the latest SW version
 */

import { NextResponse } from "next/server"

// Force dynamic rendering — we read env vars per request
export const dynamic = "force-dynamic"

export async function GET() {
  // Build the Firebase config object from environment variables
  // These are all NEXT_PUBLIC_ vars — safe to expose to clients
  const firebaseConfig = {
    apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY ?? "",
    authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN ?? "",
    projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID ?? "",
    storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET ?? "",
    messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID ?? "",
    appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID ?? "",
  }

  // ── Service worker script ─────────────────────────────────────────────────
  // Uses the Firebase compat CDN scripts (required for importScripts in SW)
  const swScript = /* javascript */ `
/**
 * Kinetic Void — Firebase Cloud Messaging Service Worker
 * Auto-generated by /app/firebase-messaging-sw.js/route.ts
 *
 * Handles:
 *   • Background push messages (app tab closed or backgrounded)
 *   • Notification click → open / focus the correct page
 *   • Raw push events (fallback for non-Firebase senders)
 */

// ── Import Firebase compat scripts ────────────────────────────────────────────
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js");

// ── Initialise Firebase (injected config, guard against double-init) ──────────
const _firebaseConfig = ${JSON.stringify(firebaseConfig)};

if (!firebase.apps.length) {
  firebase.initializeApp(_firebaseConfig);
}

const messaging = firebase.messaging();

// ── Background Message Handler ────────────────────────────────────────────────
// Fired when a push arrives and the app tab is NOT in the foreground.
//
// IMPORTANT: Registering onBackgroundMessage disables Firebase's automatic
// notification display. This handler is solely responsible for calling
// showNotification(). Do NOT return early here — doing so drops the notification.
messaging.onBackgroundMessage((payload) => {
  console.log("[FCM-SW] Background message received:", payload.data?.tag ?? "(no tag)");

  const { notification, data } = payload;

  // Prefer the richer data fields (set by send.ts) over the top-level
  // notification object, which exists primarily to wake Android when the
  // browser is fully closed.
  const title = data?.title ?? notification?.title ?? "Kinetic Void";
  const body  = data?.body  ?? notification?.body  ?? "";
  const icon  = data?.icon  ?? "/icons/icon-192.png";
  const image = data?.image ?? notification?.image;
  const url   = data?.url   ?? "/";
  const tag   = data?.tag   ?? "kinetic-void-notification";

  return self.registration.showNotification(title, {
    body,
    icon,
    badge: "/icons/icon-72.png",
    image,
    tag,
    renotify: false,
    requireInteraction: false,
    silent: false,
    vibrate: [200, 100, 200],
    timestamp: Date.now(),
    data: { url, ...data },
  });
});

// ── Notification Click Handler ────────────────────────────────────────────────
// User tapped the notification → focus or open the correct page.
self.addEventListener("notificationclick", (event) => {
  console.log("[FCM-SW] Notification clicked — tag:", event.notification.tag);

  event.notification.close();

  const targetUrl = event.notification.data?.url ?? "/";

  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clientList) => {
        // Re-use an existing open tab if possible
        for (const client of clientList) {
          const clientOrigin = new URL(client.url).origin;
          if (clientOrigin === self.location.origin) {
            client.focus();
            return client.navigate(targetUrl);
          }
        }
        // No existing tab → open a new one
        return self.clients.openWindow(targetUrl);
      })
  );
});

// ── Raw Push Event Fallback ───────────────────────────────────────────────────
// Safety net for pushes NOT sent via Firebase SDK (e.g. Supabase Edge Functions
// calling the FCM HTTP API directly with a custom payload structure).
self.addEventListener("push", (event) => {
  // Firebase SDK intercepts its own pushes in onBackgroundMessage above.
  // This handler only fires for pushes Firebase doesn't recognise.
  if (!event.data) return;

  let payload;
  try {
    payload = event.data.json();
  } catch {
    // Plain text push
    const text = event.data.text();
    event.waitUntil(
      self.registration.showNotification("Kinetic Void", {
        body: text,
        icon: "/icons/icon-192.png",
        badge: "/icons/icon-72.png",
        tag: "kv-push-fallback",
        data: { url: "/" },
      })
    );
    return;
  }

  // Only handle pushes that don't have a Firebase-style notification key
  if (payload.notification) return; // Firebase will handle it

  const { title, body, icon, url, tag } = payload.data ?? payload;
  event.waitUntil(
    self.registration.showNotification(title ?? "Kinetic Void", {
      body: body ?? "",
      icon: icon ?? "/icons/icon-192.png",
      badge: "/icons/icon-72.png",
      tag: tag ?? "kv-push",
      vibrate: [200, 100, 200],
      data: { url: url ?? "/" },
    })
  );
});

// ── Service Worker Lifecycle ──────────────────────────────────────────────────
self.addEventListener("install", () => {
  console.log("[FCM-SW] Installed — skipping waiting");
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  console.log("[FCM-SW] Activated — claiming clients");
  event.waitUntil(self.clients.claim());
});
`

  return new NextResponse(swScript, {
    status: 200,
    headers: {
      "Content-Type": "application/javascript; charset=utf-8",
      // Allow this SW to control pages at scope /
      // (required because the script URL is /firebase-messaging-sw.js,
      //  whose implicit max-scope is already /, but we set this explicitly
      //  for browser compatibility)
      "Service-Worker-Allowed": "/",
      // Never cache — always serve the latest SW with current config
      "Cache-Control": "no-cache, no-store, must-revalidate",
      "Pragma": "no-cache",
      "X-Content-Type-Options": "nosniff",
    },
  })
}
