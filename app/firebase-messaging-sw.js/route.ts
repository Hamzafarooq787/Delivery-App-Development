/**
 * app/firebase-messaging-sw.js/route.ts
 * ─────────────────────────────────────────────────────────────────────────────
 * Dynamic route handler that serves the Firebase Cloud Messaging service worker
 * at /firebase-messaging-sw.js with Firebase config values injected from
 * server-side environment variables.
 *
 * This SW is registered at scope "/" and serves as the SINGLE root service
 * worker for the application. It handles both:
 *   • FCM push notifications (background messages + notification clicks)
 *   • PWA asset caching (replacing the former static public/sw.js)
 *
 * Why a dynamic route instead of a static file in public/?
 *   Service workers cannot access process.env or window. By serving the SW
 *   through this route handler we can safely inject NEXT_PUBLIC_ Firebase
 *   config values at request time — no hardcoded credentials in the repo.
 *
 * Architecture note — why scope "/"?
 *   When the FCM SW controls the page, Firebase SDK's push event handler can
 *   distinguish foreground (visible controlled client) from background (no
 *   visible client). This is the standard Firebase architecture:
 *     page visible  → push-received message sent to page → onMessage() fires
 *     page hidden   → onBackgroundMessage() fires in SW → OS notification
 *   At the old scope "/firebase-messaging-sw.js/" the SW had no controlled
 *   clients so Firebase always called onBackgroundMessage, causing OS
 *   notifications to appear while the user was actively using the app,
 *   which triggered Chrome's notification quiet mode after 2–3 deliveries.
 */

import { NextResponse } from "next/server"

export const dynamic = "force-dynamic"

export async function GET() {
  const firebaseConfig = {
    apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY ?? "",
    authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN ?? "",
    projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID ?? "",
    storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET ?? "",
    messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID ?? "",
    appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID ?? "",
  }

  const swScript = /* javascript */ `
/**
 * Go Drop — Combined FCM + PWA Service Worker
 * Auto-generated by /app/firebase-messaging-sw.js/route.ts
 *
 * Registered at scope "/" — controls all pages.
 *
 * Responsibilities:
 *   • FCM background push messages → OS notification
 *   • FCM notification clicks → open / focus correct page
 *   • PWA offline caching (replaces former public/sw.js)
 */

// ── Firebase compat CDN (required for importScripts in SW context) ─────────────
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js");

const _firebaseConfig = ${JSON.stringify(firebaseConfig)};

if (!firebase.apps.length) {
  firebase.initializeApp(_firebaseConfig);
}

const messaging = firebase.messaging();

// ── PWA Cache ─────────────────────────────────────────────────────────────────
// Bump the version string whenever you change the precache list.
const CACHE_NAME = "kv-cache-v2";
const PRECACHE_ASSETS = [
  "/",
  "/login",
  "/signup",
  "/offline",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
];

// ── Lifecycle: Install ─────────────────────────────────────────────────────────
self.addEventListener("install", (event) => {
  console.log("[FCM-SW] Installing — scope:", self.registration.scope);
  // skipWaiting() so this SW activates immediately, replacing sw.js or the old
  // FCM SW at the narrow scope without waiting for tabs to close.
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) =>
      // Use allSettled so one 404 does not block the rest of the precache.
      Promise.allSettled(PRECACHE_ASSETS.map((url) => cache.add(url))).then((results) => {
        results.forEach((r, i) => {
          if (r.status === "rejected") {
            console.warn("[FCM-SW] Precache miss:", PRECACHE_ASSETS[i], r.reason?.message ?? r.reason);
          }
        });
      })
    )
  );
});

// ── Lifecycle: Activate ────────────────────────────────────────────────────────
self.addEventListener("activate", (event) => {
  console.log("[FCM-SW] Activated — claiming all clients, scope:", self.registration.scope);
  event.waitUntil(
    Promise.all([
      // Take control of all pages immediately (no refresh required).
      self.clients.claim(),
      // Delete caches from sw.js (kv-cache-v1) and any other stale version.
      caches.keys().then((keys) =>
        Promise.all(
          keys
            .filter((key) => key !== CACHE_NAME)
            .map((key) => {
              console.log("[FCM-SW] Deleting stale cache:", key);
              return caches.delete(key);
            })
        )
      ),
    ])
  );
});

// ── PWA Fetch Handler ─────────────────────────────────────────────────────────
self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);

  // Skip: non-GET, cross-origin, API/auth, Supabase, and the SW script itself
  if (
    request.method !== "GET" ||
    url.origin !== self.location.origin ||
    url.pathname.startsWith("/api/") ||
    url.pathname.startsWith("/auth/") ||
    url.hostname.includes("supabase") ||
    url.pathname === "/firebase-messaging-sw.js"
  ) {
    return;
  }

  // Navigations: network-first, fall back to cache then /offline
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
          }
          return response;
        })
        .catch(() =>
          caches.match(request).then((cached) => cached || caches.match("/offline"))
        )
    );
    return;
  }

  // Static assets: cache-first
  if (url.pathname.match(/\\.(js|css|png|jpg|jpeg|svg|ico|woff|woff2|ttf)$/)) {
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((response) => {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
            return response;
          })
      )
    );
  }
});


// ── FCM: Background Message Handler ───────────────────────────────────────────
// Firebase ONLY calls this handler when there is NO visible controlled client.
// When the driver has the app open and visible, Firebase sends a "push-received"
// message to the page instead, which fires the onMessage() listener in the hook.
// This means OS notifications are NEVER shown while the user is actively using
// the app — eliminating the Chrome notification quiet-mode trigger.
messaging.onBackgroundMessage((payload) => {
  console.log("[FCM-SW] Background message — tag:", payload.data?.tag ?? "(no tag)");

  const { notification, data } = payload;

  const title = data?.title ?? notification?.title ?? "Go Drop";
  const body  = data?.body  ?? notification?.body  ?? "";
  const icon  = data?.icon  ?? "/icons/icon-192.png";
  const image = data?.image ?? notification?.image;
  const url   = data?.url   ?? data?.clickAction   ?? "/";
  const tag   = data?.tag   ?? "go-drop";

  console.log("[FCM-SW] Showing OS notification:", title, "| tag:", tag);

  return self.registration.showNotification(title, {
    body,
    icon,
    badge: "/icons/icon-72.png",
    image,
    tag,
    renotify: true,
    requireInteraction: false,
    silent: false,
    vibrate: [200, 100, 200],
    timestamp: Date.now(),
    data: { url, ...data },
  });
});

// ── FCM: Notification Click Handler ───────────────────────────────────────────
self.addEventListener("notificationclick", (event) => {
  console.log("[FCM-SW] Notification clicked — tag:", event.notification.tag);

  event.notification.close();

  const targetUrl = event.notification.data?.url ?? "/";

  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clientList) => {
        for (const client of clientList) {
          if (new URL(client.url).origin === self.location.origin) {
            client.focus();
            return client.navigate(targetUrl);
          }
        }
        return self.clients.openWindow(targetUrl);
      })
  );
});

// ── Raw Push Handler ──────────────────────────────────────────────────────────
// This listener fires for EVERY push alongside Firebase's own push handler.
// Firebase's handler either:
//   • foreground (visible client): routes message to page → onMessage() → Sonner toast
//                                  but does NOT show an OS notification
//   • background (no visible client): calls onBackgroundMessage() → OS notification
//
// This handler fills the foreground gap: it shows the OS notification when the
// app is open, which Firebase skips. For background pushes with a notification
// payload it defers to onBackgroundMessage (no duplicate). For non-JSON pushes
// or data-only messages it always shows a notification.
self.addEventListener("push", (event) => {
  if (!event.data) return;

  console.log("[FCM-SW] Push event received");

  let payload;
  try {
    payload = event.data.json();
  } catch {
    // Non-JSON push — show a basic notification regardless of foreground state
    const text = event.data.text();
    event.waitUntil(
      self.registration.showNotification("Go Drop", {
        body: text,
        icon: "/icons/icon-192.png",
        badge: "/icons/icon-72.png",
        tag: "go-drop-push-fallback",
        data: { url: "/" },
      })
    );
    return;
  }

  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then(async (clients) => {
        const visibleClients = clients.filter((c) => c.visibilityState === "visible");
        const hasVisible = visibleClients.length > 0;

        console.log("[FCM-SW] clients:", clients.length, "| visible:", hasVisible);

        // Background + notification payload: onBackgroundMessage() handles it — skip
        if (!hasVisible && payload.notification) {
          console.log("[FCM-SW] Background push with notification payload — deferring to onBackgroundMessage");
          return;
        }

        const { notification, data } = payload;
        const title = data?.title ?? notification?.title ?? "Go Drop";
        const body  = data?.body  ?? notification?.body  ?? "";
        const url   = data?.url   ?? "/";
        const tag   = data?.tag   ?? "go-drop";

        console.log("[FCM-SW] Calling showNotification:", title, "| foreground:", hasVisible);

        try {
          await self.registration.showNotification(title, {
            body,
            icon:  "/icons/icon-192.png",
            badge: "/icons/icon-72.png",
            image: data?.image,
            tag,
            renotify: true,
            requireInteraction: false,
            silent: false,
            vibrate: [200, 100, 200],
            data: { url },
          });
          console.log("[FCM-SW] showNotification() succeeded");
          // Tell the page the OS notification was shown
          for (const c of visibleClients) {
            c.postMessage({ type: "FCM_SW_NOTIFICATION_SHOWN", title });
          }
        } catch (err) {
          console.error("[FCM-SW] showNotification() FAILED:", err && err.name, err && err.message);
          // Tell the page exactly why it failed so we can surface it as a toast
          for (const c of visibleClients) {
            c.postMessage({
              type: "FCM_SW_NOTIFICATION_BLOCKED",
              errorName: (err && err.name) || "Unknown",
              errorMessage: (err && err.message) || String(err),
            });
          }
        }
      })
  );
});
`

  return new NextResponse(swScript, {
    status: 200,
    headers: {
      "Content-Type": "application/javascript; charset=utf-8",
      "Service-Worker-Allowed": "/",
      "Cache-Control": "no-cache, no-store, must-revalidate",
      "Pragma": "no-cache",
      "X-Content-Type-Options": "nosniff",
    },
  })
}
